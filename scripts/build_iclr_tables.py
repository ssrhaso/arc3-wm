LADDER = [
    ("Stock DreamerV3", ("paired", "sweep"), "cold", "nothing"),
    ("State-change bonus, $\\beta{=}0.1$", ("shape01",), "cold", "reward contact"),
    ("State-change bonus, $\\beta{=}0.01$", ("shape001",), "cold", "reward contact"),
    ("Type-balanced prior", ("mixture",), "cold", "a prior over action types"),
    ("PPO, factored head$^{\\dagger}$", ("ppo",), "factored", "a factored action head"),
]
LADDER_GAMES = ["cd82", "vc33", "ls20", "sp80", "sb26", "tn36", "lf52"]


def table_ladder(rows):
    """Games as rows, interventions as columns; cell = seeds scoring, pooled clear rate, official."""
    lines = [HEADER, r"\begin{tabular}{l" + "c" * len(LADDER) + "}", r"\toprule",
             "Game & " + " & ".join(label for label, *_ in LADDER) + r" \\",
             " & " + " & ".join(f"\\emph{{{restores}}}" for *_, restores in LADDER) + r" \\",
             r"\midrule"]
    for g in LADDER_GAMES:
        vals = []
        for label, batches, arm, restores in LADDER:
            cs = cells(rows, set(batches), arm, g)
            if not cs:
                vals.append("--")
                continue
            k = sum(1 for c in cs if c["e100_official"] > 0)
            pooled = sum(round(c["e100_clear_rate"] * c["e100_n"]) for c in cs)
            n = sum(c["e100_n"] for c in cs)
            off = statistics.mean(c["e100_official"] for c in cs)
            lev = max(c["e100_levels_max"] for c in cs)
            s = f"{k}/{len(cs)}, {pooled / n:.2f}, {off:.3f}"
            if lev >= 2:
                s += f", L{lev}"
            vals.append((r"\textbf{" + s + "}") if k > 0 else s)
        lines.append(f"\\texttt{{{g}}} & " + " & ".join(vals) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines) + "\n"


