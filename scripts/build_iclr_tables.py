# ---------------------------------------------------------------- probes
def load_probe_md():
    """Paired latent minus pixel differences with CI, from the generated markdown."""
    diffs = {}
    pat = re.compile(r"^\| (\w+) \| (\w+) \| [\d.]+ \| ([\d.]+)\*? \| ([\d.]+)\*? \| ([\d.]+)\*? \| ([+-][\d.]+) \[([+-][\d.]+), ([+-][\d.]+)\]( \(ns\))? \|")
    for line in open(PROBE_MD, encoding="utf-8"):
        m = pat.match(line.strip())
        if m:
            g, t, lat, pix, clk, d, lo, hi, ns = m.groups()
            diffs[(g, t)] = dict(d=float(d), lo=float(lo), hi=float(hi), ns=bool(ns))
    return diffs


def load_probe_csv():
    acc = {}
    with open(PROBE_CSV, newline="") as f:
        for r in csv.DictReader(f):
            acc[(r["game"], r["feature"], r["target"])] = (float(r["balanced_acc"]), r["decodable"] == "True")
    return acc


def star(v, dec):
    return f"{v:.2f}" + ("$^{*}$" if dec else "")


def table_probes(acc, diffs):
    lines = [HEADER, r"\begin{tabular}{l c ccc c ccc c}", r"\toprule",
             r" & & \multicolumn{4}{c}{Level identity} & \multicolumn{4}{c}{Reward proximity} \\",
             r"\cmidrule(lr){3-6}\cmidrule(lr){7-10}",
             r"Game & chance & latent & pixel & clock & latent$-$pixel [95\% CI] & latent & pixel & clock & latent$-$pixel [95\% CI] \\",
             r"\midrule"]
    chance = {"cd82": 1 / 6, "lf52": 1 / 10, "ls20": 1 / 7, "sb26": 1 / 8, "tn36": 1 / 7, "vc33": 1 / 7}
    for g in STUDY:
        def trip(t):
            l, ld = acc[(g, "both", t)]
            p, pd = acc[(g, "pixel", t)]
            c, cd = acc[(g, "clock", t)]
            dd = diffs[(g, t)]
            ci = f"{dd['d']:+.2f} [{dd['lo']:+.2f}, {dd['hi']:+.2f}]"
            if not dd["ns"]:
                ci = r"\textbf{" + ci + "}"
            return f"{star(l, ld)} & {star(p, pd)} & {star(c, cd)} & {ci}"
        lines.append(f"\\texttt{{{g}}} & {chance[g]:.2f} & {trip('level_id')} & {trip('reward_proximity')} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------- scorecard
def table_scorecard(rows, acc, diffs):
    comp = {}
    with open(COMP, newline="") as f:
        for r in csv.DictReader(f):
            if r["source"] == "human":
                comp[r["game"]] = r
    lines = [HEADER, r"\begin{tabular}{l c c cc cc c c}", r"\toprule",
             r" & & recon.\ & \multicolumn{2}{c}{open-loop rollout} & \multicolumn{2}{c}{action-conditioning} & level id & reward prox. \\",
             r"\cmidrule(lr){4-5}\cmidrule(lr){6-7}",
             r"Game & RHAE & loss & $\Delta$ vs copy, $h{=}1$ & $\Delta$ vs copy, $H{=}8$ & sensitivity & beats copy & latent$-$pixel & latent$-$pixel \\",
             r"\midrule"]
    for g in STUDY:
        cs = stock(rows, g)
        off = statistics.mean(c["e100_official"] for c in cs)
        recon = statistics.mean(c["image_loss"] for c in cs)
        c = comp[g]
        sens = f"{100 * float(c['sensitivity']):.1f}\\%" if c["sensitivity"] else "--"
        beats = f"{100 * float(c['beats_copy_frac']):.1f}\\%" if c["beats_copy_frac"] else "--"
        lid = diffs[(g, "level_id")]
        rp = diffs[(g, "reward_proximity")]
        def mark(dd):
            s = f"{dd['d']:+.2f}"
            return s if dd["ns"] else (r"\textbf{" + s + "}")
        o = (r"\textbf{" + fmt_off(off) + "}") if off > 0 else fmt_off(off)
        lines.append(f"\\texttt{{{g}}} & {o} & {recon:.2f} & {float(c['delta_1']):+.3f} & {float(c['delta_H']):+.3f} & {sens} & {beats} & {mark(lid)} & {mark(rp)} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines) + "\n"


