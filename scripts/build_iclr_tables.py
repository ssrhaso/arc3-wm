def lf52_stats():
    """Macros and point files for the lf52 episode-length figure, from the
    authoritative ``analysis/lf52_episode_lengths.csv`` (one row per episode,
    RHAE action-count convention, phantom 0-action resets flagged)."""
    import io
    cur = ROOT / "paper" / "iclr-2027" / "curves"
    src = ROOT / "analysis" / "lf52_episode_lengths.csv"
    lines = [l for l in open(src) if not l.startswith("#")]
    rows = list(csv.DictReader(io.StringIO("".join(lines))))
    human = [r for r in rows if r["series"] == "human" and r["is_phantom"] == "0"]
    agent = [r for r in rows if r["series"] != "human"]
    hs = sorted(int(r["action_count"]) for r in human)
    wins = sorted(int(r["action_count"]) for r in human if r["terminal_state"] == "WIN")
    others = sorted(int(r["action_count"]) for r in human if r["terminal_state"] != "WIN")
