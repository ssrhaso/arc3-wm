def table_ladder_full(rows):
    """Two tabulars (left, right) so the per-seed listing fits one page side by side."""
    arms = [("Bonus $\\beta{=}0.1$", "shape01", "cold"), ("Bonus $\\beta{=}0.01$", "shape001", "cold"),
            ("Type-balanced prior", "mixture", "cold"), ("5M steps", "long5m", "cold"),
            ("Update ratio 512", "ratio512", "cold"), ("PPO flat$^{\\dagger}$", "ppo", "flat"),
            ("PPO factored$^{\\dagger}$", "ppo", "factored")]
    body = []
    for label, batch, arm in arms:
        rs = sorted([r for r in rows if r["batch"] == batch and r["arm"] == arm], key=lambda r: (r["game"], r["seed"]))
        body.append(f"\\multicolumn{{5}}{{l}}{{\\emph{{{label}}}}} \\\\")
        for c in rs:
            k = round(c["e100_clear_rate"] * c["e100_n"])
            lo, hi = wilson(k, c["e100_n"])
            body.append(f"\\texttt{{{c['game']}}} & {c['seed']} & {c['e100_clear_rate']:.2f} [{lo:.2f}, {hi:.2f}] & {fmt_off(c['e100_official'])} & {c['e100_levels_max']} \\\\")
        body.append(r"\addlinespace[1pt]")
    half = (len(body) + 1) // 2
    head = [r"\begin{tabular}{lc c c c}", r"\toprule",
            r"Game & seed & clear rate [95\% CI] & official & levels \\", r"\midrule"]
    tail = [r"\bottomrule", r"\end{tabular}"]
    left = "\n".join(head + body[:half] + tail)
    right = "\n".join(head + body[half:] + tail)
    return HEADER + "\\begin{minipage}[t]{0.49\\linewidth}\\centering\n" + left + "\n\\end{minipage}\\hfill\n\\begin{minipage}[t]{0.49\\linewidth}\\centering\n" + right + "\n\\end{minipage}\n"


