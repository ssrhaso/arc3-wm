def wilson(k: int, n: int, z: float = 1.96) -> tuple[float, float]:
    if n <= 0:
        return (0.0, 0.0)
    p = k / n
    den = 1 + z * z / n
    centre = (p + z * z / (2 * n)) / den
    half = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / den
    return (max(centre - half, 0.0), min(centre + half, 1.0))


def load_agg() -> list[dict]:
    rows = []
    with open(AGG, newline="") as f:
        for r in csv.DictReader(f):
            if r["done"] != "True" or r["e100_n"] in ("", "0"):
                continue
            r["seed"] = int(r["seed"])
            for k in ("e100_clear_rate", "e100_official", "e100_official_mean",
                      "norm_entropy", "image_loss"):
                r[k] = float(r[k]) if r[k] not in ("", "nan") else float("nan")
            r["e100_n"] = int(r["e100_n"])
            r["e100_levels_max"] = int(r["e100_levels_max"])
            r["train_clears"] = int(r["train_clears"]) if r["train_clears"] else 0
            r["train_eps"] = int(r["train_eps"]) if r["train_eps"] else 0
            rows.append(r)
    return rows


def cells(rows, batch, arm, game):
    out = [r for r in rows if r["batch"] in batch and r["arm"] == arm and r["game"] == game]
    return sorted(out, key=lambda r: r["seed"])


def stock(rows, game):
    """Stock DreamerV3: paired cold (seeds 2-4) for the study games, sweep cold otherwise."""
    return cells(rows, {"paired"} if game in STUDY else {"sweep"}, "cold", game)


def fmt_rate(c):
    return f"{c['e100_clear_rate']:.2f}".replace("0.", ".") if c["e100_clear_rate"] < 1 else "1.00"


def fmt_off(x):
    return f"{x:.4f}"


def random_floor() -> dict[str, dict]:
    from arc3_wm import official_rhae as O  # noqa: WPS433 (needs the venv)
    out = {}
    for d in sorted(RANDOM_DIR.glob("*-masked")):
        game = d.name.split("-")[0]
        eps = [json.loads(l)["rewards"] for l in open(d / "eval_episodes.jsonl") if l.strip()]
        b = O.load_official_baselines(game, ROOT / "environment_files")
        res = O.compute_official_rhae(episodes_rewards=eps, game_id=game, baselines=b)
        key = [k for k in res if "per_game" in k][0]
        out[game] = {"n": len(eps), "clears": sum(1 for e in eps if any(r > 0 for r in e)),
                     "official": float(res[key])}
    return out


# ---------------------------------------------------------------- main table
def table_main(rows, floor):
    lines = [HEADER, r"\begin{tabular}{l ccc c c cc}", r"\toprule",
             r" & \multicolumn{3}{c}{Stock DreamerV3, 3 seeds} & Random floor & & \multicolumn{2}{c}{PPO flat, 2 seeds} \\",
             r"\cmidrule(lr){2-4}\cmidrule(lr){5-5}\cmidrule(lr){7-8}",
             r"Game & clear rate per seed & official & levels & official (clears/300) & entropy & clear rate & official \\",
             r"\midrule"]
    scorers = [g for g in ALL25 if any(c["e100_official"] > 0 for c in stock(rows, g))]
    zeros = [g for g in ALL25 if g not in scorers]
    for g in scorers + ["__sep__"] + STUDY_ZERO_ORDER(zeros):
        if g == "__sep__":
            lines.append(r"\midrule")
            continue
        cs = stock(rows, g)
        rates = ", ".join(fmt_rate(c) for c in cs)
        off = statistics.mean(c["e100_official"] for c in cs)
        lev = max(c["e100_levels_max"] for c in cs)
        ent = statistics.mean(c["norm_entropy"] for c in cs)
        fl = floor.get(g)
        fl_s = (f"{fl['official']:.4f}" if fl['official'] >= 5e-5 else f"{fl['official']:.0e}") + f" ({fl['clears']}/{fl['n']})" if fl else "--"
        ppo = cells(rows, {"ppo"}, "flat", g)
        ppo_r = ", ".join(fmt_rate(c) for c in ppo) if ppo else "--"
        ppo_o = ", ".join(fmt_off(c["e100_official"]) for c in ppo) if ppo else "--"
        bold = (lambda s: r"\textbf{" + s + "}") if off > 0 else (lambda s: s)
        lines.append(f"\\texttt{{{g}}} & {rates} & {bold(fmt_off(off))} & {lev} & {fl_s} & {ent:.3f} & {ppo_r} & {ppo_o} \\\\")
    mean25 = statistics.mean(statistics.mean(c["e100_official"] for c in stock(rows, g)) for g in ALL25)
    lines += [r"\midrule",
              f"Mean over 25 games & & {mean25:.4f} & & & & & \\\\",
              r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines) + "\n", mean25, scorers


def STUDY_ZERO_ORDER(zeros):
    """Study games first among the zeros, then the rest alphabetically."""
    return [g for g in STUDY if g in zeros] + [g for g in zeros if g not in STUDY]


